#!/usr/bin/env python3
"""Create a minimal local DeerFlow demo configuration."""

from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path


@dataclass(frozen=True)
class BootstrapResult:
    relative_path: str
    status: str


def bootstrap_demo(project_root: Path | str, *, force: bool = False) -> list[BootstrapResult]:
    root = Path(project_root).resolve()
    root.mkdir(parents=True, exist_ok=True)

    config_version = _read_config_version(root / "config.example.yaml")
    files = {
        "config.yaml": _build_config_yaml(config_version),
        ".env": _build_env_file(),
        "frontend/.env": _build_frontend_env_file(),
        "extensions_config.json": _json({"mcpServers": {}, "skills": {}}),
        "registries/demo_extensions.json": _json(_demo_registry()),
    }

    results: list[BootstrapResult] = []
    for relative_path, content in files.items():
        target = root / relative_path
        if target.exists() and not force:
            results.append(BootstrapResult(relative_path, "skipped"))
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
        results.append(BootstrapResult(relative_path, "written"))
    return results


def _read_config_version(example_path: Path) -> int:
    if not example_path.exists():
        return 15
    match = re.search(r"^config_version:\s*(\d+)\s*$", example_path.read_text(encoding="utf-8"), re.MULTILINE)
    return int(match.group(1)) if match else 15


