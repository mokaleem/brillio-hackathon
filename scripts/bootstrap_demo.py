def _json(data: dict) -> str:
    return json.dumps(data, indent=2) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Create minimal local demo config files.")
    parser.add_argument("--project-root", default=Path(__file__).resolve().parents[1], type=Path)
    parser.add_argument("--force", action="store_true", help="Overwrite existing generated files.")
    args = parser.parse_args(argv)

    results = bootstrap_demo(args.project_root, force=args.force)
    for result in results:
        marker = "wrote" if result.status == "written" else "kept"
        print(f"{marker}: {result.relative_path}")
    print("")
    print("Next:")
    print("  1. Add OPENAI_API_KEY to .env")
    print("  2. Run make doctor")
    print("  3. Run make dev")
    return 0


if __name__ == "__main__":
    sys.exit(main())
